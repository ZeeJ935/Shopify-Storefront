// Builds the expected answers the backend's SQL catalog must match: the old
// in-memory logic (rawFromSnapshot) run on the fixture catalog.
//   npx tsx scripts/catalog-parity.ts --write   → writes backend/test/fixtures/catalog-parity.json
// scripts/audit-unit.ts checks the committed file is up to date.
import fs from "node:fs";
import path from "node:path";
import { rawFromSnapshot } from "../lib/catalog-query";
import { fixtureInputs, fixtureSnapshot } from "./catalog-fixture";

export const PARITY_FILE = path.join(__dirname, "../backend/test/fixtures/catalog-parity.json");

export function buildParity() {
  const snapshot = fixtureSnapshot();
  return {
    note: "Generated by scripts/catalog-parity.ts from the old in-memory catalog logic. Do not edit by hand.",
    products: snapshot.products,
    collections: Object.fromEntries(Object.entries(snapshot.collectionIds).map(([handle, ids]) => [handle, [...ids]])),
    bestSelling: snapshot.bestSellingOrder,
    cases: fixtureInputs().map((input) => {
      const raw = rawFromSnapshot(snapshot, input);
      return { input, expected: { ...raw, products: raw.products.map((p) => p.id) } };
    }),
  };
}

export const parityJson = () => JSON.stringify(buildParity(), null, 1) + "\n";

if (process.argv.includes("--write")) {
  fs.writeFileSync(PARITY_FILE, parityJson());
  console.log(`wrote ${path.relative(process.cwd(), PARITY_FILE)}`);
}
